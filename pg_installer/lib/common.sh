# ── 색상 / 출력 함수 ─────────────────────────────────────────
BOLD='\033[1m'; GREEN='\033[0;32m'; CYAN='\033[0;36m'
YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'

info()  { echo -e "  ${GREEN}✔${NC}  $*"; }
warn()  { echo -e "  ${YELLOW}⚠${NC}  $*"; }
error() { echo -e "  ${RED}✘${NC}  $*"; exit 1; }
phase() { local _txt="$*"
          local _len=${#_txt} _line
          _line=$(printf '━%.0s' $(seq 1 $(( _len + 4 ))))
          echo -e "\n${CYAN}${BOLD}  ${_line}${NC}"
          echo -e "${CYAN}${BOLD}    ${_txt}${NC}"
          echo -e "${CYAN}${BOLD}  ${_line}${NC}"; }
div()   { echo -e "  ─────────────────────────────────────────────"; }

# ============================================================
#  공통 함수 모음
# ============================================================

# ── postgresql.conf 생성 함수 ────────────────────────────────
# 인자: $1=출력파일 $2=CPU수 $3=메모리GB $4=모드(single|ha) $5=ARC_PATH
fn_gen_conf() {
    local OUT="$1" CPU="$2" MEM="$3" MODE="$4" ARC="$5"
    local MEM_KB=$(( MEM * 1024 * 1024 ))
    local SHR_MB=$(( MEM_KB / 4 / 1024 ))
    local EFF_MB=$(( MEM_KB * 3 / 4 / 1024 ))
    local MAX_CONN=150
    local WORK_MB=$(( (MEM_KB / 4) / MAX_CONN / 1024 ))
    [[ $WORK_MB -lt 4   ]] && WORK_MB=4
    local MAINT_MB=$(( MEM_KB / 20 / 1024 ))
    [[ $MAINT_MB -lt 64   ]] && MAINT_MB=64
    [[ $MAINT_MB -gt 2048 ]] && MAINT_MB=2048
    local WAL_BUF_MB=$(( SHR_MB * 3 / 100 ))
    [[ $WAL_BUF_MB -lt 1  ]] && WAL_BUF_MB=1
    [[ $WAL_BUF_MB -gt 64 ]] && WAL_BUF_MB=64
    local MIN_WAL=$(( MEM * 1024 / 16 ))
    [[ $MIN_WAL -lt 256  ]] && MIN_WAL=256
    local MAX_WAL=$(( MEM * 1024 / 4 ))
    [[ $MAX_WAL -lt 1024 ]] && MAX_WAL=1024
    local KEEP_WAL=$(( MAX_WAL / 2 ))
    [[ $KEEP_WAL -lt 512 ]] && KEEP_WAL=512
    local PARA=$(( CPU / 2 ))
    [[ $PARA -lt 1 ]] && PARA=1
    # lc_messages: 없는 로케일을 지정하면 서버가 기동 실패(FATAL)하므로
    # en_US.utf8 이 있을 때만 쓰고 없으면 C (영문 메시지는 동일)
    local LC_MSG="C"
    if locale -a 2>/dev/null | grep -qiE '^en_US\.utf-?8$'; then LC_MSG="en_US.utf8"; fi

    cat > "${OUT}" <<CONFEOF
# ============================================================
#  postgresql.conf  (Generated by postgresql_install.sh v1.0)
#  CPU: ${CPU}  MEM: ${MEM}GB  Mode: ${MODE}
# ============================================================

# ── 접속 설정 ──────────────────────────────────────────────
listen_addresses = '*'
port             = ${PG_PORT}
max_connections  = ${MAX_CONN}

# ── 메모리 설정 ────────────────────────────────────────────
shared_buffers          = ${SHR_MB}MB
effective_cache_size    = ${EFF_MB}MB
work_mem                = ${WORK_MB}MB
maintenance_work_mem    = ${MAINT_MB}MB

# ── WAL 설정 ───────────────────────────────────────────────
wal_buffers                  = ${WAL_BUF_MB}MB
checkpoint_completion_target = 0.9
wal_level                    = replica
min_wal_size                 = ${MIN_WAL}MB
max_wal_size                 = ${MAX_WAL}MB
wal_keep_size                = ${KEEP_WAL}MB
CONFEOF

    if [[ -n "${ARC}" ]]; then
        cat >> "${OUT}" <<CONFEOF
archive_mode    = on
archive_command = 'test ! -f ${ARC}/%f && cp %p ${ARC}/%f'   # 이미 있는 파일은 덮어쓰지 않음
CONFEOF
    else
        cat >> "${OUT}" <<CONFEOF
archive_mode    = off
# archive_command = ''
CONFEOF
    fi

    cat >> "${OUT}" <<CONFEOF

# ── 병렬 처리 ──────────────────────────────────────────────
max_worker_processes             = ${CPU}
max_parallel_workers_per_gather  = ${PARA}
max_parallel_workers             = ${CPU}

# ── 로그 설정 ──────────────────────────────────────────────
logging_collector = on
log_directory     = '${LOG_PATH}'
log_filename      = 'postgresql-%Y-%m-%d.log'
log_rotation_age  = 1d
log_rotation_size = 100MB
log_statement     = 'ddl'
log_min_duration_statement = 1000
log_line_prefix   = '%t [%p]: [%l-1] user=%u,db=%d,app=%a,client=%h '
log_checkpoints   = on
log_connections   = on
log_disconnections= on
log_lock_waits    = on

# ── 쿼리 통계 (pgmon Statement / pg_tune_ai) ──────────────
shared_preload_libraries   = 'pg_stat_statements'
pg_stat_statements.max     = 10000
pg_stat_statements.track   = top
track_io_timing            = on

# ── 타임존 / 로케일 ────────────────────────────────────────
timezone          = 'Asia/Seoul'
lc_messages       = '${LC_MSG}'
lc_monetary       = '${PG_LOCALE}'
lc_numeric        = '${PG_LOCALE}'
lc_time           = '${PG_LOCALE}'
CONFEOF

    if [[ "${MODE}" == "ha" ]]; then
        cat >> "${OUT}" <<CONFEOF

# ── HA Replication 설정 ────────────────────────────────────
max_wal_senders       = 10
max_replication_slots = 10
CONFEOF
    fi
}

# ── PKG rpm 설치 함수 (로컬) ─────────────────────────────────
fn_install_pkg_local() {
    if [[ -f "${PKG_TGZ}" ]]; then
        info "의존 패키지(rpm) 설치 중..."
        local TMP
        TMP=$(mktemp -d)
        tar -zxf "${PKG_TGZ}" -C "${TMP}" >> "${LOG_INSTALL}" 2>&1
        #sudo rpm -Uvh --force "${TMP}"/PKG/*.rpm >> "${LOG_INSTALL}" 2>&1 || true
	sudo dnf localinstall -y "${TMP}"/PKG/*.rpm >> "${LOG_INSTALL}" 2>&1 || true
        rm -rf "${TMP}"
        info "의존 패키지 설치 완료"
    else
        warn "PKG.tar.gz 없음. 의존패키지가 사전 설치되어 있어야 합니다."
    fi
}

# ── PG 빌드 함수 (로컬) ──────────────────────────────────────
fn_build_pg_local() {
    local BUILD_CPU="${1:-${CPU_CORES}}"

    # ── 빌드 도구 확인 (PKG 에 빠졌으면 configure 전에 명확히 멈춤) ──
    local _need=() _t
    for _t in gcc make bison flex; do command -v "${_t}" &>/dev/null || _need+=("${_t}"); done
    if [[ ${#_need[@]} -gt 0 ]]; then
        error "빌드 도구 없음: ${_need[*]}
    PKG 에 rpm 이 제대로 들어있지 않습니다:  ls ${INSTALLER_DIR}/../PKG | wc -l
    pg_download.sh 로 다시 받은 뒤 installer/PKG.tar.gz 를 지우고 재실행하세요."
    fi

    # ── configure 옵션 ──────────────────────────────────────
    #  installer/build_features.txt (pg_download.sh 생성) 의 BASE 는 항상,
    #  FEATURE 는 라이브러리(-devel)가 실제로 설치돼 있는 것만 켠다.
    #  (PKG 에 -devel 이 빠졌을 때 configure 자체가 실패하지 않도록)
    #  ※ 마이너 업그레이드 시 같은 옵션으로 다시 빌드해야 하므로
    #    ${ENGINE_PATH}/etc/configure_options.txt 에 기록한다 (pg_config --configure 로도 확인 가능)
    local CONF_OPTS=(--prefix="${ENGINE_PATH}")
    local _skipped=() _t _a _b _c
    _has_pc() { pkg-config --exists "$1" 2>/dev/null; }
    local FEAT_FILE="${INSTALLER_DIR}/build_features.txt"
    if [[ -f "${FEAT_FILE}" ]]; then
        # pg_download.sh 가 받은 PG 소스의 configure 기준으로 만든 목록
        #   BASE|옵션  /  FEATURE|이름|옵션|pkg-config
        while IFS='|' read -r _t _a _b _c; do
            case "${_t}" in
                BASE)    CONF_OPTS+=("${_a}") ;;
                FEATURE) if _has_pc "${_c}"; then CONF_OPTS+=("${_b}"); else _skipped+=("${_a}(${_c})"); fi ;;
            esac
        done < <(grep -v '^#' "${FEAT_FILE}")
    else
        # build_features.txt 가 없는 구버전 패키지 → 기본 규칙
        CONF_OPTS+=(--with-openssl --with-libxml --with-libxslt
                    --enable-nls --with-python --with-tcl --with-perl)
        if _has_pc liblz4;     then CONF_OPTS+=(--with-lz4);       else _skipped+=("lz4(lz4-devel)"); fi
        if _has_pc libzstd;    then CONF_OPTS+=(--with-zstd);      else _skipped+=("zstd(libzstd-devel)"); fi
        if _has_pc libsystemd; then CONF_OPTS+=(--with-systemd);   else _skipped+=("systemd(systemd-devel)"); fi
        if _has_pc uuid;       then CONF_OPTS+=(--with-uuid=e2fs); else _skipped+=("uuid-ossp(libuuid-devel)"); fi
        if [[ "${PG_MAJOR}" -ge 18 ]]; then
            if _has_pc liburing; then CONF_OPTS+=(--with-liburing); else _skipped+=("io_uring(liburing-devel)"); fi
        fi
    fi

    info "PostgreSQL 소스 빌드 중 (make -j${BUILD_CPU})..."
    info "  configure: ${CONF_OPTS[*]:1}"
    if [[ ${#_skipped[@]} -gt 0 ]]; then
        warn "  -devel 없어서 제외: ${_skipped[*]}"
    fi

    local TMP
    TMP=$(mktemp -d)
    tar -zxf "${PG_TARBALL}" -C "${TMP}" >> "${LOG_INSTALL}" 2>&1
    pushd "${TMP}/postgresql-${PG_VERSION}" > /dev/null
    ./configure "${CONF_OPTS[@]}" \
        >> "${LOG_INSTALL}" 2>&1 || error "configure 실패. 로그: ${LOG_INSTALL}"
    make -j"${BUILD_CPU}"  >> "${LOG_INSTALL}" 2>&1 || error "make 실패"
    make install           >> "${LOG_INSTALL}" 2>&1 || error "make install 실패"
    # contrib (pg_stat_statements, pg_buffercache, pgstattuple, uuid-ossp 등) 빌드/설치
    cd contrib
    make -j"${BUILD_CPU}"  >> "${LOG_INSTALL}" 2>&1 || true
    make install           >> "${LOG_INSTALL}" 2>&1 || true
    cd ..
    popd > /dev/null
    rm -rf "${TMP}"

    mkdir -p "${ENGINE_PATH}/etc"
    {
        echo "# PostgreSQL ${PG_VERSION} 빌드 옵션 ($(date '+%Y-%m-%d %H:%M:%S'))"
        echo "# 마이너 업그레이드 시 같은 옵션으로 configure 하세요 (prefix 는 새 경로로 바꿔도 됨)"
        echo "./configure ${CONF_OPTS[*]}"
        if [[ ${#_skipped[@]} -gt 0 ]]; then
            echo "# -devel 없어서 제외된 옵션: ${_skipped[*]}"
        fi
    } > "${ENGINE_PATH}/etc/configure_options.txt"
    info "PostgreSQL 빌드 및 설치 완료 → ${ENGINE_PATH} (contrib 포함)"
    info "  빌드 옵션 기록 → ${ENGINE_PATH}/etc/configure_options.txt"
}

# ── Extension 소스 빌드 함수 (로컬) ──────────────────────────
#  pg_download.sh 가 installer/extensions/ 에 넣어둔 *.tar.gz (GitHub 태그
#  tarball) 를 PGXS 로 빌드해서 엔진 경로에 설치한다.
#  HA 모드에서는 etcd 서버에서 빌드한 엔진을 그대로 scp 하므로 함께 배포된다.
fn_build_extensions_local() {
    local BUILD_CPU="${1:-${CPU_CORES}}"
    local EXT_SRC="${INSTALLER_DIR}/extensions"
    local PG_CONFIG_BIN="${ENGINE_PATH}/bin/pg_config"
    local _tars=() _t _name _dir _ok=0 _fail=0 _preload=()

    shopt -s nullglob
    _tars=("${EXT_SRC}"/*.tar.gz)
    shopt -u nullglob
    [[ ${#_tars[@]} -eq 0 ]] && return 0

    info "extension 소스 빌드 중 (${#_tars[@]}개, PGXS)..."
    for _t in "${_tars[@]}"; do
        _name=$(basename "${_t}" .tar.gz)
        _dir=$(mktemp -d)
        # 카탈로그의 make_args (예: pgvector OPTFLAGS=) — 이름 "<key>-<ref>" 로 매칭
        local _margs=()
        if [[ -f "${EXT_SRC}/manifest.json" ]] && command -v python3 &>/dev/null; then
            read -r -a _margs <<< "$(python3 - "${EXT_SRC}/manifest.json" "${_name}" <<'PY'
import sys, json
m = json.load(open(sys.argv[1])); n = sys.argv[2]
for k, v in m.get("extensions", {}).items():
    if n.startswith(k + "-"):
        print(v.get("make_args", "")); break
PY
)"
        fi
        if tar -xzf "${_t}" -C "${_dir}" --strip-components=1 >> "${LOG_INSTALL}" 2>&1 && \
           ( cd "${_dir}" && \
             make USE_PGXS=1 PG_CONFIG="${PG_CONFIG_BIN}" "${_margs[@]}" -j"${BUILD_CPU}" && \
             make USE_PGXS=1 PG_CONFIG="${PG_CONFIG_BIN}" "${_margs[@]}" install ) >> "${LOG_INSTALL}" 2>&1; then
            info "  ✔ ${_name}"
            _ok=$(( _ok + 1 ))
            # shared_preload_libraries 등록이 필요한 extension 안내용
            case "${_name}" in
                pg_cron*|pgaudit*|pg_stat_kcache*|pg_qualstats*|pg_wait_sampling*|pg_stat_monitor*)
                    _preload+=("${_name%%-*}") ;;
            esac
        else
            warn "  ✘ ${_name} 빌드 실패 — 로그: ${LOG_INSTALL}"
            _fail=$(( _fail + 1 ))
        fi
        rm -rf "${_dir}"
    done
    info "extension 빌드 완료: 성공 ${_ok} / 실패 ${_fail}"
    if [[ ${#_preload[@]} -gt 0 ]]; then
        warn "아래 extension 은 shared_preload_libraries 등록 + 재시작 후 CREATE EXTENSION 하세요:"
        warn "  ${_preload[*]}"
    fi
    return 0
}

# ── 디렉토리 생성 함수 (로컬) ────────────────────────────────
fn_create_dirs_local() {
    mkdir -p "${ENGINE_PATH}/etc" "${DATA_PATH}" "${LOG_PATH}"
    [[ -n "${ARC_PATH}"  ]] && mkdir -p "${ARC_PATH}"
    [[ -n "${BACK_PATH}" ]] && mkdir -p "${BACK_PATH}"
    # dump 디렉토리는 DUMP_PATH가 실제로 설정된 경우(backup=y)에만 생성.
    # Archive/Backup을 모두 사용하지 않으면(=n) 임의 경로(/pgbackup 등)를
    # 권한 없이 생성 시도하지 않도록 생략한다. 필요 시 사용자가 직접 생성.
    [[ -n "${DUMP_PATH}" ]] && mkdir -p "${DUMP_PATH}"
    return 0
}

# ── sudo 권한 확인 함수 (원격) ───────────────────────────────
fn_check_sudo_remote() {
    local HOST="$1"
    local SSH_OPTS="$2"
    info "[${HOST}] sudo NOPASSWD 권한 확인 중..."
    if ssh ${SSH_OPTS} "${HOST}" "sudo -n true" >> "${HA_LOG}" 2>&1; then
        info "[${HOST}] sudo 권한 확인 완료"
    else
        error "[${HOST}] sudo NOPASSWD 권한이 없습니다.
  아래 명령어를 ${HOST} 서버에서 root 로 실행해주세요:
  echo '$(whoami) ALL=(ALL) NOPASSWD: ALL' > /etc/sudoers.d/$(whoami)
  chmod 440 /etc/sudoers.d/$(whoami)"
    fi
}

# ── .postgresrc 생성 함수 ────────────────────────────────────
fn_gen_postgresrc() {
    local OUT="$1"
    # DUMP_PATH 기본값: backup=y 면 DUMP_PATH 변수, 아니면 ARC_BASE/dump 또는 /pgbackup/dump
    local _DUMP_PATH="${DUMP_PATH:-${ARC_BASE:-/pgbackup}/dump}"
    local _BACK_PATH_RC="${BACK_PATH:-${ARC_BASE:-/pgbackup}/back}"
    cat > "${OUT}" <<RCEOF
# PostgreSQL Environment
export PGHOME=${ENGINE_PATH}
export PATH=\${PGHOME}/bin:\${PATH}
export LD_LIBRARY_PATH=\${PGHOME}/lib:\${LD_LIBRARY_PATH}
export PGDATA=${DATA_PATH}
export PGPORT=${PG_PORT}
export PGUSER=postgres
export PGDATABASE=postgres

# ── 편의 alias ─────────────────────────────────────────────
alias pgbin='cd \${PGHOME}/bin'
alias pgetc='cd ${ENGINE_PATH}/etc'
alias pgdata='cd ${DATA_PATH}'
alias pgback='cd ${_BACK_PATH_RC}'
alias pgdump='cd ${_DUMP_PATH}'
alias pglog='cd ${LOG_PATH}'
alias pgstart='\${PGHOME}/bin/pg_ctl -D ${DATA_PATH} -l ${LOG_PATH}/startup.log start'
alias pgstop='\${PGHOME}/bin/pg_ctl -D ${DATA_PATH} stop'
alias pgstat='\${PGHOME}/bin/pg_ctl -D ${DATA_PATH} status'
alias pgreload='\${PGHOME}/bin/pg_ctl -D ${DATA_PATH} reload'
alias psql='\${PGHOME}/bin/psql'
RCEOF
}
